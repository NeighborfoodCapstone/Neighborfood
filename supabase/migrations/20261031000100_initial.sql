-- Do not change privileges on unrelated tables or sequences in public.
DO $$
DECLARE
    role_name text;
    object_name text;
BEGIN
    FOREACH role_name IN ARRAY ARRAY['anon', 'authenticated'] LOOP
        IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = role_name) THEN
            FOREACH object_name IN ARRAY ARRAY['users', 'sessions', 'auth_codes', 'posts', 'transactions', 'groupbuy_participants', 'manner_ratings', 'settlements', 'settlement_shares', 'qr_sessions', 'receipts', 'wishlists', 'conversations', 'messages', 'conversation_members', 'fridge_items', 'notices', 'reports', 'location_verify_sessions', 'portone_test_payments', 'portone_quick_test_payments', 'neighborfood_schema_version'] LOOP
                EXECUTE format('REVOKE ALL ON TABLE public.%I FROM %I', object_name, role_name);
            END LOOP;
            FOREACH object_name IN ARRAY ARRAY['users', 'posts', 'transactions', 'manner_ratings', 'settlements', 'conversations', 'messages', 'notices', 'reports'] LOOP
                EXECUTE format('REVOKE ALL ON SEQUENCE %s FROM %I',
                    pg_get_serial_sequence(format('public.%I', object_name), 'id'), role_name);
            END LOOP;
        END IF;
    END LOOP;
END $$;
