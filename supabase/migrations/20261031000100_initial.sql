-- Canonical Supabase baseline; preserve unrelated public and managed-schema objects.
-- The migration runner supplies the transaction.
SET LOCAL search_path = public, pg_catalog;
CREATE TABLE users (
                id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                login_id        TEXT    UNIQUE NOT NULL,
                password_hash   TEXT    NOT NULL,
                phone_number    TEXT    UNIQUE NOT NULL,
                nickname        TEXT,
                profile_image   TEXT,
                trust_score     DOUBLE PRECISION    NOT NULL DEFAULT 36.5,
                role            TEXT    NOT NULL DEFAULT 'user'
                                CHECK (role   IN ('user', 'admin')),
                status          TEXT    NOT NULL DEFAULT 'active'
                                CHECK (status IN ('active', 'suspended', 'withdrawn')),
                neighborhood    TEXT,
                neighborhood_verified_at TEXT,
                email           TEXT,
                bio             TEXT,
                interests       TEXT,
                dietary         TEXT,
                created_at      TEXT    NOT NULL,
                updated_at      TEXT    NOT NULL
            );

CREATE TABLE sessions (
                token      TEXT    PRIMARY KEY,
                user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                expires_at TEXT    NOT NULL,
                created_at TEXT    NOT NULL
            );

CREATE TABLE auth_codes (
                phone_number TEXT PRIMARY KEY,
                code         TEXT NOT NULL,
                expiry_time  TEXT NOT NULL
            );

CREATE TABLE posts (
                id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                type          TEXT    NOT NULL,
                title         TEXT    NOT NULL,
                description   TEXT,
                category      TEXT,
                images        TEXT    DEFAULT '[]',
                address       TEXT,
                lat           DOUBLE PRECISION,
                lng           DOUBLE PRECISION,
                author_id     BIGINT NOT NULL REFERENCES users(id),
                status        TEXT    DEFAULT 'active',
                created_at    TEXT    NOT NULL,
                expires_at    TEXT,
                gb_target     BIGINT,
                gb_current    BIGINT DEFAULT 0,
                gb_price      BIGINT,
                exchange_want TEXT,
                appointment_place TEXT,
                appointment_at    TEXT,
                appointment_lat   DOUBLE PRECISION,
                appointment_lng   DOUBLE PRECISION
            );

CREATE TABLE transactions (
                id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                post_id       BIGINT NOT NULL REFERENCES posts(id),  -- 이력 보존(CASCADE 제거)
                provider_id   BIGINT NOT NULL REFERENCES users(id),  -- 나눔/판매자
                receiver_id   BIGINT          REFERENCES users(id),  -- 수령자
                status        TEXT    NOT NULL DEFAULT 'pending'
                              CHECK (status IN ('pending', 'confirmed', 'completed', 'canceled')),
                qr_session_id TEXT,    -- 연계된 qr_sessions.id (선택)
                receipt_id    TEXT,    -- 연계된 receipts.id    (선택)
                appointment_at TEXT,   -- 거래 약속 일시(ISO, 선택)
                created_at    TEXT    NOT NULL,
                completed_at  TEXT
            );

CREATE TABLE groupbuy_participants (
                post_id   BIGINT NOT NULL REFERENCES posts(id),
                user_id   BIGINT NOT NULL REFERENCES users(id),
                joined_at TEXT    NOT NULL,
                PRIMARY KEY (post_id, user_id)
            );

CREATE TABLE manner_ratings (
                id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                transaction_id BIGINT NOT NULL REFERENCES transactions(id),
                rater_id       BIGINT NOT NULL REFERENCES users(id),
                ratee_id       BIGINT NOT NULL REFERENCES users(id),
                score          BIGINT NOT NULL CHECK (score IN (-1, 1)),
                comment        TEXT,
                created_at     TEXT    NOT NULL,
                UNIQUE (transaction_id, rater_id)
            );

CREATE TABLE settlements (
                id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                post_id           BIGINT NOT NULL REFERENCES posts(id),
                requester_id      BIGINT NOT NULL REFERENCES users(id),
                total_amount      BIGINT NOT NULL,
                account_info      TEXT,
                status            TEXT NOT NULL DEFAULT 'pending'
                                  CHECK (status IN ('pending','completed','canceled')),
                appointment_place TEXT,
                appointment_at    TEXT,
                appointment_lat   DOUBLE PRECISION,
                appointment_lng   DOUBLE PRECISION,
                created_at        TEXT NOT NULL,
                completed_at      TEXT
            );

CREATE TABLE settlement_shares (
                settlement_id  BIGINT NOT NULL REFERENCES settlements(id),
                user_id        BIGINT NOT NULL REFERENCES users(id),
                amount         BIGINT NOT NULL,
                status         TEXT NOT NULL DEFAULT 'unpaid'
                               CHECK (status IN ('unpaid','paid','noshow')),
                gps_verified   BIGINT NOT NULL DEFAULT 0,
                quality_agreed BIGINT NOT NULL DEFAULT 0,
                auto_confirmed BIGINT NOT NULL DEFAULT 0,
                paid_at        TEXT,
                created_at     TEXT NOT NULL,
                PRIMARY KEY (settlement_id, user_id)
            );

CREATE TABLE qr_sessions (
                id                 TEXT PRIMARY KEY,
                subject_id         TEXT NOT NULL,
                purpose            TEXT NOT NULL,
                token_hash         TEXT NOT NULL UNIQUE,
                status             TEXT NOT NULL DEFAULT 'ISSUED'
                                   CHECK (status IN ('ISSUED', 'VERIFIED', 'EXPIRED')),
                issued_at          TEXT NOT NULL,
                expires_at         TEXT NOT NULL,
                used_at            TEXT,
                last_scanned_at    TEXT,
                scanner_ip         TEXT,
                scanner_user_agent TEXT,
                created_at         TEXT NOT NULL,
                updated_at         TEXT NOT NULL
            );

CREATE TABLE receipts (
            id TEXT PRIMARY KEY,
            subject_id TEXT,
            store_name TEXT,
            purchased_at TEXT,
            items TEXT NOT NULL DEFAULT '[]',
            selected_items TEXT NOT NULL DEFAULT '[]',
            total BIGINT,
            status TEXT NOT NULL DEFAULT 'SCANNED'
                CHECK (status IN ('SCANNED', 'VERIFIED', 'FAILED')),
            trust_delta DOUBLE PRECISION NOT NULL DEFAULT 0,
            ocr_engine TEXT,
            image_path TEXT,
            scanned_at TEXT NOT NULL,
            verified_at TEXT,
            created_at TEXT NOT NULL,
            updated_at TEXT NOT NULL
        , safe_ocr_text TEXT, ocr_result_json TEXT, raw_ocr_json TEXT, shopping_matches_json TEXT NOT NULL DEFAULT '[]', shopping_match_status TEXT NOT NULL DEFAULT 'NOT_REQUESTED', shopping_matched_at TEXT, fridge_added_at TEXT);

CREATE TABLE wishlists (
                user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                post_id    BIGINT NOT NULL REFERENCES posts(id),
                created_at TEXT    NOT NULL,
                PRIMARY KEY (user_id, post_id)
            );

CREATE TABLE conversations (
                id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                post_id    BIGINT NOT NULL REFERENCES posts(id),
                host_id    BIGINT NOT NULL REFERENCES users(id),
                guest_id   BIGINT NOT NULL REFERENCES users(id),
                created_at TEXT    NOT NULL, kind TEXT NOT NULL DEFAULT 'direct',
                UNIQUE (post_id, guest_id)
            );

CREATE TABLE messages (
                id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                conversation_id BIGINT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
                sender_id       BIGINT NOT NULL REFERENCES users(id),
                content         TEXT    NOT NULL,
                created_at      TEXT    NOT NULL,
                read_at         TEXT
            );

CREATE TABLE conversation_members (
                conversation_id BIGINT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
                user_id         BIGINT NOT NULL REFERENCES users(id),
                last_read_id    BIGINT NOT NULL DEFAULT 0,
                joined_at       TEXT    NOT NULL,
                PRIMARY KEY (conversation_id, user_id)
            );

CREATE TABLE fridge_items (
          id TEXT PRIMARY KEY,
          user_id BIGINT,
          receipt_id TEXT,
          source TEXT NOT NULL DEFAULT 'receipt',
          item_name TEXT NOT NULL,
          qty BIGINT NOT NULL DEFAULT 1,
          unit TEXT,
          price BIGINT DEFAULT 0,
          category TEXT,
          store_name TEXT,
          purchased_at TEXT,
          status TEXT NOT NULL DEFAULT 'ACTIVE'
            CHECK (status IN ('ACTIVE', 'CONSUMED', 'EXPIRED', 'DISCARDED')),
          created_at TEXT NOT NULL,
          updated_at TEXT NOT NULL, expiry_date TEXT, memo TEXT, quantity_text TEXT,
          UNIQUE(receipt_id, item_name, purchased_at)
        );

CREATE TABLE notices (
                id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                author_id  BIGINT REFERENCES users(id),
                title      TEXT    NOT NULL,
                content    TEXT    NOT NULL,
                created_at TEXT    NOT NULL
            );

CREATE TABLE reports (
                id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                reporter_id BIGINT NOT NULL REFERENCES users(id),
                target_type TEXT    NOT NULL CHECK (target_type IN ('post','user')),
                target_id   BIGINT NOT NULL,
                reason      TEXT    NOT NULL,
                status      TEXT    NOT NULL DEFAULT 'pending'
                            CHECK (status IN ('pending','resolved','dismissed')),
                created_at  TEXT    NOT NULL
            );

CREATE TABLE location_verify_sessions (
